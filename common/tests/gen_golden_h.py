"""gen_golden_h.py -- data/exl3_golden.npz -> exl3_golden.h, so the C test reads the golden with no zip reader.

    python3 gen_golden_h.py data/exl3_golden.npz exl3_golden.h        write it
    python3 gen_golden_h.py data/exl3_golden.npz exl3_golden.h --check exit 1 if the committed header differs

The npz is a byte copy of Dylan's exl3-moe tests/data/exl3_golden.npz (exl3-moe 8428c31, sha256
321e617054aaaa11334133c0088c1903d2743dd344baf99ca159453ac1d4e754): vllm-exl3's host decode (dequant_cpu)
of random trellises, K = 3, 4 x codebooks mcg, mul1; its own `provenance` string is copied into the header.
`--check` is the ctest that keeps the two copies of the fact from drifting (exit 77 = SKIPPED without numpy).
"""
import sys


def render(npz_path):
    import numpy as np

    z = np.load(npz_path)
    out = ["/* exl3_golden.h -- GENERATED by gen_golden_h.py from data/exl3_golden.npz; do not edit.",
           " * provenance: " + str(z["provenance"]),
           " * W_hat is exllamav3's [k, n] = [16*kt, 16*nt], fp16 bits. */",
           "#include <stdint.h>", "",
           "typedef struct Exl3GoldenCase { int bits; const char* codebook; int kt, nt;",
           "                                const uint16_t* trellis; const uint16_t* w_hat; } Exl3GoldenCase;", ""]
    cases = []
    for bits in (3, 4):
        for cb in ("mcg", "mul1"):
            tr = z[f"trellis_k{bits}_{cb}"]
            wh = z[f"w_hat_k{bits}_{cb}"]
            kt, nt, w = tr.shape
            assert w == 16 * bits and wh.shape == (16 * kt, 16 * nt)
            for name, arr in ((f"k{bits}_{cb}_trellis", tr), (f"k{bits}_{cb}_w_hat", wh)):
                vals = arr.astype(np.int16).view(np.uint16).ravel()
                body = ",".join(f"0x{v:04x}" for v in vals)
                out.append(f"static const uint16_t exl3_golden_{name}[{vals.size}] = {{{body}}};")
            cases.append(f"    {{ {bits}, \"{cb}\", {kt}, {nt}, exl3_golden_k{bits}_{cb}_trellis, "
                         f"exl3_golden_k{bits}_{cb}_w_hat }},")
    out += ["", "static const Exl3GoldenCase exl3_golden_cases[] = {"] + cases + ["};",
            "enum { EXL3_GOLDEN_N = (int)(sizeof exl3_golden_cases / sizeof exl3_golden_cases[0]) };", ""]
    return "\n".join(out)


def main(argv):
    if len(argv) not in (3, 4) or (len(argv) == 4 and argv[3] != "--check"):
        print(__doc__)
        return 2
    try:
        text = render(argv[1])
    except ImportError:
        print("SKIPPED: numpy is not installed")
        return 77
    if len(argv) == 4:
        with open(argv[2]) as f:
            same = f.read() == text
        print("golden header matches the npz" if same else "FAIL: exl3_golden.h differs from the npz; regenerate it")
        return 0 if same else 1
    with open(argv[2], "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
